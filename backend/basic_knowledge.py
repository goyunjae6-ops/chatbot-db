def normalize(text):
    return re.sub(r'[\s?!！？.,~。"“”\'’]+', '', text.lower())


FOLLOWUPS = {
    '더자세히': 'detail', '더자세히알려줘': 'detail', '자세히설명해줘': 'detail',
    '더알려줘': 'detail', '쉽게설명해줘': 'summary', '쉽게말해줘': 'summary',
    '쉽게': 'summary', '한줄로': 'summary', '요약해줘': 'summary', '정리해줘': 'summary',
    '예시': 'example', '예시보여줘': 'example', '예제': 'example', '예제보여줘': 'example',
    '코드예제': 'example', '예를들어줘': 'example', '문제내줘': 'quiz', '퀴즈내줘': 'quiz',
    '문제': 'quiz', '정답': 'answer', '정답알려줘': 'answer', '답알려줘': 'answer',
}


def find_card(text):
    compact = normalize(text)
    # These are subject matches, not fuzzy guesses or a general-purpose model.
    hits = [(len(normalize(key)), item) for item in CARDS for key in item['keys'] if normalize(key) in compact]
    return max(hits, key=lambda hit: hit[0])[1] if hits else None


def followup_field(text):
    compact = normalize(text)
    if compact in FOLLOWUPS:
        return FOLLOWUPS[compact]
    patterns = [
        (r'(?:좀|조금)?더?(?:자세히|자세하게)(?:알려줘|설명해줘|설명해줄래|설명해줄수있어)?(?:요)?', 'detail'),
        (r'(?:좀|조금)?(?:더)?쉽게(?:알려줘|설명해줘|말해줘|설명해줄래)(?:요)?', 'summary'),
        (r'(?:예시|예제|코드예제)(?:를)?(?:좀)?(?:보여줘|알려줘|보여줄래)(?:요)?', 'example'),
        (r'(?:연습)?(?:문제|퀴즈)(?:를)?(?:하나|좀)?내줘(?:요)?', 'quiz'),
        (r'(?:정답|해설)(?:을)?(?:좀)?(?:알려줘|보여줘)(?:요)?', 'answer'),
    ]
    return next((field for pattern, field in patterns if re.fullmatch(pattern, compact)), None)


def knowledge_reply(text, previous):
    compact = normalize(text)
    if any(word in compact for word in ('차이', '비교', '달라')):
        for subjects, title, answer in COMPARISONS:
            if all(subject in compact for subject in subjects):
                return f'[{title} 비교]\n{answer}'
    field = followup_field(text)
    item = None
    if field:
        for recent in reversed(previous[-8:]):
            if followup_field(recent):
                continue
            item = find_card(recent)
            break
        if item is None:
            return None
    else:
        item = find_card(text)
        if item is None:
            return None
        field = 'summary'
        if any(word in compact for word in ('예시', '예제')):
            field = 'example'
        elif any(word in compact for word in ('자세히', '원리')):
            field = 'detail'
        elif '문제내' in compact or '퀴즈내' in compact:
            field = 'quiz'
    if field == 'quiz':
        return f'[{item["title"]} 연습 문제]\n{item["quiz"]}\n\n“정답”이라고 하면 등록된 해설을 볼 수 있어요.'
    if field == 'answer':
        return f'[{item["title"]} 등록 문제의 정답]\n{item["answer"]}'
    if field == 'example':
        return f'[{item["title"]} 예시]\n{item["example"]}'
    if field == 'detail':
        return f'{item["summary"]}\n\n{item["detail"]}\n\n{item["example"]}'
    return f'{item["summary"]}\n\n{item["example"]}\n\n“더 자세히”, “문제 내줘”로 이어서 물어볼 수 있어요. 등록된 설명을 안내하는 기본 모드예요.'
